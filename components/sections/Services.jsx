// ── Single service card ──────────────────────────────────────────────────────
function ServiceCard({ item, index }) {
  const [expanded, setExpanded] = useState(false);

  return (
    <motion.div
      initial={{ opacity: 0, y: 40 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: '-30px' }}
      transition={{ delay: index * 0.08, duration: 0.6 }}
      onMouseEnter={() => setExpanded(true)}
      onMouseLeave={() => setExpanded(false)}
      onFocus={() => setExpanded(true)}
      onBlur={() => setExpanded(false)}
      className={`card-hover group relative p-6 md:p-8 rounded-2xl bg-charcoal cursor-default transition-all duration-300 ${
        expanded ? 'border-gold' : 'border-white/5 border'
      }`}
      style={expanded ? { boxShadow: '0 8px 32px rgba(212, 168, 67, 0.15)' } : {}}
    >
      {/* Icon */}
      <div
        className={`inline-flex p-3 rounded-xl mb-5 transition-colors duration-300 ${
          expanded ? 'bg-gold/20 text-gold' : 'bg-white/5 text-white/40'
        }`}
      >
        {ICONS[item.icon] || ICONS.Wrench}
      </div>

      {/* Title */}
      <h3 className="font-heading font-black text-lg mb-2 text-white leading-snug">
        {item.title}
      </h3>

      {/* Description */}
      <p
        className={`text-sm leading-relaxed transition-all duration-300 ${
          expanded ? 'text-white/70' : 'text-white/40'
        }`}
      >
        {expanded ? item.full : item.short}
      </p>

      {/* Gold accent line on hover */}
      <div
        className={`absolute bottom-0 left-6 right-6 h-px bg-gradient-to-r from-transparent via-gold to-transparent transition-opacity duration-300 ${
          expanded ? 'opacity-100' : 'opacity-0'
        }`}
        aria-hidden
      />
    </motion.div>
  );
}

